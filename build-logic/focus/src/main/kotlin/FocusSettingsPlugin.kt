import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.artifacts.ProjectDependency
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.initialization.Settings
import org.gradle.api.provider.SetProperty
import org.gradle.api.tasks.Delete
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * Lets a developer work on one module without Gradle and Android Studio loading the whole app:
 *
 * ```
 * ./gradlew :feature:orders:sandbox:focus   // then sync: only that module and what it depends on
 * ./gradlew clearFocus                      // then sync: the whole project again
 * ```
 *
 * The modules live in `settings-all.gradle.kts`. `focus` writes the module with all its project
 * dependencies (transitively, every configuration – tests and KSP too) to `.focus`, a per-developer
 * file outside git. While it exists, only those modules are included.
 */
class FocusSettingsPlugin : Plugin<Settings> {
    override fun apply(settings: Settings) = with(settings) {
        val focusFile = settingsDir.resolve(FOCUS_FILE)
        val focused = providers.fileContents(layout.rootDirectory.file(FOCUS_FILE)).asText.orNull
            ?.lines()?.map(String::trim)?.filter { it.isNotEmpty() && !it.startsWith("#") }

        if (focused == null) {
            apply(mapOf("from" to settingsDir.resolve("settings-all.gradle.kts")))
        } else {
            focused.forEach(::include)
            println("Focus: ${focused.size} modules from $FOCUS_FILE – ./gradlew clearFocus to load the whole project")
        }

        gradle.lifecycle.beforeProject {
            if (this == rootProject) {
                tasks.register("clearFocus", Delete::class.java) {
                    description = "Loads the whole project again (after a Gradle sync)."
                    delete(focusFile)
                }
            } else {
                val project = this
                tasks.register("focus", FocusTask::class.java) {
                    description = "Loads only this module and its dependencies (after a Gradle sync)."
                    projectPaths.set(provider { project.withProjectDependencies() })
                    this.focusFile.set(focusFile)
                }
            }
        }
    }

    private companion object {
        const val FOCUS_FILE = ".focus"
    }
}

/** This project and every project it depends on, directly or not, in any configuration. */
private fun Project.withProjectDependencies(): Set<String> {
    val visited = sortedSetOf<String>()
    fun visit(project: Project) {
        if (!visited.add(project.path)) return
        project.configurations.forEach { configuration ->
            configuration.dependencies.withType(ProjectDependency::class.java).forEach { visit(project.project(it.path)) }
        }
    }
    visit(this)
    return visited
}

@DisableCachingByDefault(because = "Writes a local, per-developer file")
abstract class FocusTask : DefaultTask() {

    @get:Input
    abstract val projectPaths: SetProperty<String>

    @get:OutputFile
    abstract val focusFile: RegularFileProperty

    @TaskAction
    fun write() {
        val paths = projectPaths.get()
        focusFile.get().asFile.writeText(
            buildString {
                appendLine("# Generated by ./gradlew ${path} – remove with ./gradlew clearFocus")
                paths.forEach(::appendLine)
            },
        )
        logger.lifecycle("Focused on ${path.removeSuffix(":focus")}: ${paths.size} modules. Sync Android Studio to load only them.")
    }
}
